function formatChunksForPrompt(
  segmentChunks: SourceChunk[],
  maxCharsPerChunk = 540,
  maxChunks = 6
): string {
  // Spread the picks across the WHOLE segment instead of only keeping its first chunks
  const n = segmentChunks.length;
  const picked =
    n <= maxChunks || maxChunks < 2
      ? segmentChunks.slice(0, maxChunks)
      : Array.from(
          { length: maxChunks },
          (_, i) => segmentChunks[Math.floor((i * (n - 1)) / (maxChunks - 1))]
        );
  return picked
    .map(
      (c) =>
        `[${c.fileName} · P.${c.pageNumber}] (${c.ueCode} - ${c.chapterTitle})\n${selectHighValueText(
          c.content,
          maxCharsPerChunk
        )}`
    )
    .join("\n\n");
}

function computePageRangeLabel(segmentChunks: SourceChunk[]): string {
  if (segmentChunks.length === 0) return "P.1";
  let minP = Infinity;
  let maxP = 0;
  for (const c of segmentChunks) {
    if (c.pageNumber < minP) minP = c.pageNumber;
    if (c.pageNumber > maxP) maxP = c.pageNumber;
  }
  if (!Number.isFinite(minP)) return "P.1";
  return minP === maxP ? `P.${minP}` : `P.${minP}–${maxP}`;
}

/**
 * Streaming plain-text call (no JSON mode). Uses native node:http/https streaming with
 * >= 1200s (20 min) timeout and keeps partial text if interrupted.
 */
async function callOllamaText(
  prompt: string,
  options?: {
    system?: string;
    timeoutMs?: number;
    numPredict?: number;
    temperature?: number;
    shouldStop?: () => boolean;
  }
): Promise<string | null> {
  const timeoutMs = Math.max(options?.timeoutMs ?? OLLAMA_TIMEOUT_MS, OLLAMA_TIMEOUT_MS);
  const numPredict = options?.numPredict ?? 1700;
  const systemPrompt = options?.system
    ? `${options.system}\n${OLLAMA_STRICT_SYSTEM_RULE}`
    : OLLAMA_STRICT_SYSTEM_RULE;

  return withOllamaLock(async () => {
    if (options?.shouldStop?.()) return null;
    const health = await checkOllamaHealth({ useCache: true });
    if (!health.online) return null;

    const { model } = getOllamaConfig();
    let acc = "";

    try {
      const res = await ollamaPostStream(
        "/api/generate",
        {
          model,
          system: systemPrompt,
          prompt,
          keep_alive: OLLAMA_KEEP_ALIVE,
          stream: true,
          options: getOllamaInferenceOptions({
            temperature: options?.temperature,
            num_predict: numPredict,
            repeat_penalty: 1.15,
          }),
        },
        timeoutMs
      );
      if (!res.ok || !res.stream) return null;

      const reader = res.stream.getReader();
      const decoder = new TextDecoder();
      let buffer = "";
      for (;;) {
        if (options?.shouldStop?.()) {
          res.abort();
          return null;
        }
        const { done, value } = await reader.read();
        if (done) break;
        buffer += decoder.decode(value, { stream: true });
        let nl = buffer.indexOf("\n");
        while (nl >= 0) {
          const line = buffer.slice(0, nl).trim();
          buffer = buffer.slice(nl + 1);
          if (line) {
            try {
              const obj = JSON.parse(line) as { response?: string };
              if (obj.response) acc += obj.response;
            } catch {
              // Ignore partial NDJSON line
            }
          }
          nl = buffer.indexOf("\n");
        }
      }
      return acc.trim() || null;
    } catch (err) {
      if (options?.shouldStop?.()) return null;
      console.warn("[Studio] Ollama text stream warning:", err);
      return acc.trim() || null;
    }
  });
}

export interface ContextWindow {
  text: string;
  chunks: SourceChunk[];
  pageRange: string;
  wordCount: number;
}

/**
 * num_ctx = 8192 tokens ≈ ~5500–6000 French words TOTAL (system + instructions + input + output).
 * Keeping each input window <= 2000 words / <= 12000 chars prevents silent context truncation
 * even on 150–300 page handouts while preserving headroom for structured output tokens.
 */
const MAX_WORDS_PER_CONTEXT_WINDOW = 2000;
const MAX_CHARS_PER_CONTEXT_WINDOW = 12000;

export function countWords(text: string): number {
  const trimmed = text.trim();
  if (!trimmed) return 0;
  return trimmed.split(/\s+/).length;
}

export function hasUsableChunksText(
  chunks: Array<{ content: string }>
): boolean {
  if (!Array.isArray(chunks) || chunks.length === 0) return false;
  const combined = chunks
    .map((c) => cleanChunkTextForAi(c.content || ""))
    .join(" ");
  return hasUsableText(combined);
}

function truncateToContextBudget(
  text: string,
  maxWords = MAX_WORDS_PER_CONTEXT_WINDOW,
  maxChars = MAX_CHARS_PER_CONTEXT_WINDOW
): string {
  let trimmed = text.trim();
  if (trimmed.length > maxChars) {
    trimmed = trimmed.slice(0, maxChars);
    const lastSpace = trimmed.lastIndexOf(" ");
    if (lastSpace > Math.floor(maxChars * 0.7)) {
      trimmed = trimmed.slice(0, lastSpace);
    }
  }
  const words = trimmed.split(/\s+/);
  if (words.length > maxWords) {
    trimmed = words.slice(0, maxWords).join(" ");
  }
  return trimmed.trim();
}

function splitSingleOversizedPiece(
  text: string,
  maxWords: number,
  maxChars: number
): string[] {
  if (countWords(text) <= maxWords && text.length <= maxChars) {
    return [text];
  }
  const words = text.split(/\s+/);
  const parts: string[] = [];
  let cur: string[] = [];
  let curChars = 0;

  for (const word of words) {
    const nextChars = curChars + word.length + (cur.length > 0 ? 1 : 0);
    if (cur.length > 0 && (cur.length + 1 > maxWords || nextChars > maxChars)) {
      parts.push(cur.join(" "));
      cur = [];
      curChars = 0;
    }
    cur.push(word);
    curChars += word.length + (cur.length > 1 ? 1 : 0);
  }
  if (cur.length > 0) {
    parts.push(cur.join(" "));
  }
  return parts;
}

function stripSequentialChunkOverlap(
  prevText: string,
  nextText: string
): string {
  const maxCheck = Math.min(160, prevText.length, nextText.length);
  for (let len = maxCheck; len >= 24; len -= 1) {
    if (nextText.startsWith(prevText.slice(prevText.length - len))) {
      return nextText.slice(len).trimStart();
    }
  }
  return nextText;
}

/**
 * Splits the ENTIRE selected course (all chunks in document & page order) into consecutive
 * context-window-safe segments processed sequentially one after another so large handouts
 * NEVER exceed num_ctx (6144) or suffer silent truncation.
 */
function splitChunksIntoContextWindows(
  chunks: SourceChunk[],
  opts?: {
    maxWords?: number;
    maxChars?: number;
    maxWindows?: number;
    targetMinWindows?: number;
  }
): ContextWindow[] {
  const maxWordsCap = Math.min(
    opts?.maxWords ?? MAX_WORDS_PER_CONTEXT_WINDOW,
    MAX_WORDS_PER_CONTEXT_WINDOW
  );
  const maxCharsCap = Math.min(
    opts?.maxChars ?? MAX_CHARS_PER_CONTEXT_WINDOW,
    MAX_CHARS_PER_CONTEXT_WINDOW
  );
  const maxWindows = opts?.maxWindows ?? 40;

  const sorted = [...chunks].sort((a, b) =>
    a.documentId === b.documentId
      ? a.pageNumber - b.pageNumber
      : a.documentId.localeCompare(b.documentId)
  );

  const pieces: Array<{ chunk: SourceChunk; text: string; words: number }> = [];
  let prevChunkRef: SourceChunk | null = null;
  let prevCleaned = "";
  for (const chunk of sorted) {
    let cleaned = cleanChunkTextForAi(chunk.content);
    if (
      prevChunkRef &&
      prevChunkRef.documentId === chunk.documentId &&
      prevChunkRef.pageNumber === chunk.pageNumber &&
      prevCleaned
    ) {
      cleaned = stripSequentialChunkOverlap(prevCleaned, cleaned);
    }
    prevChunkRef = chunk;
    prevCleaned = cleanChunkTextForAi(chunk.content);
    if (cleaned.length < 20) continue;
    const subTexts = splitSingleOversizedPiece(cleaned, maxWordsCap, maxCharsCap);
    for (const sub of subTexts) {
      pieces.push({ chunk, text: sub, words: countWords(sub) });
    }
  }

  if (pieces.length === 0) return [];

  const totalWords = pieces.reduce((sum, p) => sum + p.words, 0);
  const totalChars = pieces.reduce((sum, p) => sum + p.text.length + 12, 0);

  let effectiveMaxWords = maxWordsCap;
  let effectiveMaxChars = maxCharsCap;

  if (opts?.targetMinWindows && opts.targetMinWindows > 1 && pieces.length > 1) {
    const desired = Math.min(opts.targetMinWindows, pieces.length);
    const wordsPerTarget = Math.ceil(totalWords / desired);
    const charsPerTarget = Math.ceil(totalChars / desired);
    if (wordsPerTarget < effectiveMaxWords && wordsPerTarget >= 180) {
      effectiveMaxWords = wordsPerTarget;
    }
    if (charsPerTarget < effectiveMaxChars && charsPerTarget >= 1200) {
      effectiveMaxChars = charsPerTarget;
    }
  }

  const windows: ContextWindow[] = [];
  let curPieces: typeof pieces = [];
  let curWords = 0;
  let curChars = 0;

  const flush = () => {
    if (curPieces.length === 0) return;
    const parts: string[] = [];
    let lastPage = -1;
    let lastDoc = "";
    for (const p of curPieces) {
      let prefix = "";
      if (p.chunk.documentId !== lastDoc) {
        prefix += `[DOCUMENT : ${p.chunk.fileName}] `;
        lastDoc = p.chunk.documentId;
        lastPage = -1;
      }
      if (p.chunk.pageNumber !== lastPage) {
        prefix += `[P.${p.chunk.pageNumber}] `;
        lastPage = p.chunk.pageNumber;
      }
      parts.push(`${prefix}${p.text}`);
    }
    const winChunks = curPieces.map((p) => p.chunk);
    const text = truncateToContextBudget(
      parts.join("\n"),
      maxWordsCap,
      maxCharsCap
    );
    windows.push({
      text,
      chunks: winChunks,
      pageRange: computePageRangeLabel(winChunks),
      wordCount: countWords(text),
    });
    curPieces = [];
    curWords = 0;
    curChars = 0;
  };

  for (const piece of pieces) {
    const pieceChars = piece.text.length + 18;
    if (
      curPieces.length > 0 &&
      (curWords + piece.words > effectiveMaxWords ||
        curChars + pieceChars > effectiveMaxChars)
    ) {
      flush();
    }
    curPieces.push(piece);
    curWords += piece.words;
    curChars += pieceChars;
  }
  flush();

  if (windows.length <= maxWindows) {
    return windows;
  }

  // Only if an extraordinary document produces > maxWindows, sample evenly across the entire document
  return Array.from(
    { length: maxWindows },
    (_, i) => windows[Math.floor((i * (windows.length - 1)) / (maxWindows - 1))]
  );
}

interface ParsedSummaryMarkdown {
  title?: string;
  subsections: SummarySubSection[];
  pitfalls: string[];
}

const EMOJI_PATTERN =
  "(?:[\\uD800-\\uDBFF][\\uDC00-\\uDFFF]|[\\u2190-\\u2BFF])\\uFE0F?";
const ICON_RE = new RegExp(`^(${EMOJI_PATTERN})\\s*(.*)$`);
const CALLOUT_RE = new RegExp(
  `^(${EMOJI_PATTERN})?\\s*(?:\\*\\*([^*]+)\\*\\*)?\\s*[:：]?\\s*(.*)$`
);

function stripMd(text: string): string {
  return text.replace(/\*\*/g, "").replace(/^[#>\s]+/, "").trim();
}

/** Deterministic parser for the markdown the model is asked to produce. */
function parseSummaryMarkdown(raw: string): ParsedSummaryMarkdown {
  const lines = raw.replace(/\r/g, "").split("\n");
  let title: string | undefined;
  const subsections: SummarySubSection[] = [];
  const pitfalls: string[] = [];
  let inPitfalls = false;
  let tableBuf: string[] = [];
  const holder: { current: SummarySubSection | null } = { current: null };

  const ensureCurrent = (): SummarySubSection => {
    if (!holder.current) {
      holder.current = {
        icon: "📌",
        title: "Points essentiels",
        callouts: [],
        bullets: [],
        table: null,
      };
      subsections.push(holder.current);
    }
    return holder.current;
  };

  const flushTable = () => {
    if (tableBuf.length >= 2) {
      const parsedRows = tableBuf.map((l) =>
        l
          .replace(/^\|/, "")
          .replace(/\|$/, "")
          .split("|")
          .map((c) => c.trim())
      );
      const headers = parsedRows[0];
      const rawBody = parsedRows
        .slice(1)
        .filter((r) => !r.every((c) => /^:?-{2,}:?$/.test(c)));

      const seenRowKeys = new Set<string>();
      const uniqueRows: string[][] = [];
      for (const r of rawBody) {
        const normalized = headers.map((_, i) => r[i] ?? "");
        const joined = normalized.join(" ").trim();
        if (
          !joined ||
          /^(?:valeur|colonne [a-z0-9]|donn[ée]e\s*(?:r[ée]elle\s*)?[a-z0-9]+|[ée]l[ée]ment\s*r[ée]el\s*[a-z0-9]+|caract[ée]ristique\s*\d|\.{3}|-)+$/i.test(
            joined
          ) ||
          normalized.some((cell) => hasGenericPlaceholderLeak(cell))
        ) {
          continue;
        }
        const key = normalized.map((c) => c.toLowerCase()).join("|");
        if (seenRowKeys.has(key)) continue;
        seenRowKeys.add(key);
        uniqueRows.push(normalized);
      }

      if (headers.length >= 2 && uniqueRows.length >= 2) {
        const cur = ensureCurrent();
        if (!cur.table) {
          cur.table = {
            headers,
            rows: uniqueRows,
          };
        }
      }
    }
    tableBuf = [];
  };

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();

    if (trimmed.startsWith("|")) {
      tableBuf.push(trimmed);
      continue;
    }
    if (tableBuf.length > 0) flushTable();
    if (!trimmed || /^```/.test(trimmed) || /^-{3,}$/.test(trimmed)) continue;

    const titleMatch = trimmed.match(/^(?:TITRE|TITLE)\s*:\s*(.+)$/i);
    if (titleMatch) {
      title = stripMd(titleMatch[1]);
      continue;
    }
    const h1 = trimmed.match(/^#\s+(.+)$/);
    if (h1) {
      title = title || stripMd(h1[1]);
      continue;
    }

    const h2 = trimmed.match(/^#{2,4}\s+(.+)$/);
    if (h2) {
      inPitfalls = false;
      const text = h2[1].trim();
      const im = text.match(ICON_RE);
      const sub: SummarySubSection = {
        icon: im ? im[1] : "📌",
        title: stripMd(im ? im[2] : text) || "Points essentiels",
        callouts: [],
        bullets: [],
        table: null,
      };
      subsections.push(sub);
      holder.current = sub;
      continue;
    }

    if (
      !/^[-*•]\s/.test(trimmed) &&
      /^(?:#{1,4}\s*)?(?:⚠️\s*)?(?:\*\*)?(?:PI[ÈE]GES|Points? de vigilance)\b/i.test(
        trimmed
      )
    ) {
      inPitfalls = true;
      continue;
    }

    if (trimmed.startsWith(">")) {
      const inner = trimmed.replace(/^>\s*/, "");
      const m = inner.match(CALLOUT_RE);
      const icon = m?.[1] || "💡";
      const ctitle = (m?.[2] || "À retenir").replace(/\s*[:：]\s*$/, "").trim();
      const text = (m?.[3] || "").trim();
      if (text || m?.[2]) {
        ensureCurrent().callouts!.push({
          type: icon.startsWith("🚨")
            ? "ALERT"
            : icon.startsWith("⚠")
            ? "RULE"
            : icon.startsWith("📅")
            ? "KEY_DATE"
            : "DEFINITION",
          icon,
          title: ctitle,
          text: text || undefined,
        });
      }
      continue;
    }

    const bulletMatch = rawLine.match(/^(\s*)(?:[-*•]|\d+[.)])\s+(.*)$/);
    if (bulletMatch) {
      const indent = bulletMatch[1].replace(/\t/g, "  ").length;
      const body = bulletMatch[2].trim();
      if (!body) continue;

      if (inPitfalls) {
        pitfalls.push(stripMd(body));
        continue;
      }

      const cur = ensureCurrent();
      const lastBullet = cur.bullets![cur.bullets!.length - 1];
      if (indent >= 2 && lastBullet) {
        lastBullet.subItems = [...(lastBullet.subItems || []), body];
        continue;
      }

      const lm = body.match(/^\*\*([^*]+)\*\*\s*[:：\-–]?\s*(.*)$/);
      if (lm && lm[2].trim()) {
        cur.bullets!.push({
          lead: lm[1].replace(/\s*[:：]\s*$/, "").trim(),
          text: lm[2].trim(),
        });
      } else {
        cur.bullets!.push({ text: body });
      }
      continue;
    }

    if (inPitfalls) {
      pitfalls.push(stripMd(trimmed));
      continue;
    }

    const cur = ensureCurrent();
    if (
      !cur.intro &&
      cur.bullets!.length === 0 &&
      cur.callouts!.length === 0
    ) {
      cur.intro = trimmed;
    } else {
      cur.bullets!.push({ text: trimmed });
    }
  }
  if (tableBuf.length > 0) flushTable();

  return {
    title,
    pitfalls,
    subsections: subsections.filter(
      (s) =>
        (s.callouts?.length || 0) > 0 ||
        (s.bullets?.length || 0) > 0 ||
        Boolean(s.table) ||
        Boolean(s.intro)
    ),
  };
}

export async function generateStudioArtifact(params: {
  kind: StudioArtifactKind;
  chunks: SourceChunk[];
  title?: string;
  prompt?: string;
  isPublic?: boolean;
  pageImagesBase64?: PageImageInput[];
  onProgress?: (percent: number, detailLabel: string) => void;
  shouldStop?: () => boolean;
}): Promise<{
  title: string;
  content: StudioArtifactContent;
  usedAi: boolean;
  emptySourceText?: boolean;
}> {
  const {
    kind,
    chunks,
    prompt,
    isPublic = false,
    pageImagesBase64,
    onProgress,
    shouldStop,
  } = params;
  const fullCourseMode = Boolean(isPublic);
  const sources = buildSourceRefs(chunks);

  const orderedChunks = fullCourseMode
    ? [...chunks]
    : [
        ...chunks.filter((c) => c.content.includes("[REPÈRE VISUEL")),
        ...chunks.filter((c) => !c.content.includes("[REPÈRE VISUEL")),
      ];

  const defaultTopic =
    prompt?.trim().slice(0, 72) ||
    chunks[0]?.documentTitle ||
    chunks[0]?.ueTitle ||
    "Synthèse de cours";

  // Hard safety guard: never call Ollama on empty/scanned PDFs with no usable text
  if (!hasUsableChunksText(orderedChunks)) {
    const uniqueDocIds = Array.from(
      new Set(orderedChunks.map((c) => c.documentId).filter(Boolean))
    );
    console.error(
      `[Studio] Génération ${kind} annulée : texte extrait vide ou PDF scanné sans texte exploitable (documents: ${
        uniqueDocIds.join(", ") || "aucun"
      }). Aucun appel Ollama effectué.`
    );
    if (uniqueDocIds.length === 1) {
      await setDocumentProcessingStatus(
        uniqueDocIds[0],
        "ERROR",
        "PDF scanné ou sans texte exploitable (OCR requis)"
      ).catch(() => null);
    }

    if (kind === "FLASHCARDS") {
      return {
        title: params.title?.trim() || `Flashcards — ${defaultTopic}`,
        usedAi: false,
        emptySourceText: true,
        content: { kind: "FLASHCARDS", cards: [], sources },
      };
    }
    if (kind === "QUIZ") {
      return {
        title: params.title?.trim() || `Quiz — ${defaultTopic}`,
        usedAi: false,
        emptySourceText: true,
        content: { kind: "QUIZ", questions: [], sources },
      };
    }
    if (kind === "SVG_DIAGRAM") {
      const emptyTitle = params.title?.trim() || `Schéma : ${defaultTopic}`;
      const svg = compileSwissEditorialSvg({
        title: emptyTitle,
        subtitle: "PDF sans texte exploitable",
        layout: "FLOW",
        nodes: [],
        edges: [],
        sources,
      });
      return {
        title: emptyTitle,
        usedAi: false,
        emptySourceText: true,
        content: {
          kind: "SVG_DIAGRAM",
          title: emptyTitle,
          subtitle: "PDF sans texte exploitable",
          layout: "FLOW",
          nodes: [],
          edges: [],
          svg,
          sources,
        },
      };
    }
    return {
      title: params.title?.trim() || `Fiche — ${defaultTopic}`,
      usedAi: false,
      emptySourceText: true,
      content: {
        kind: "SUMMARY",
        pipeline: "FULL_V3",
        overview: "Aucun texte exploitable détecté dans ce document (PDF scanné ou vide).",
        sections: [],
        keyConcepts: [],
        examPitfalls: [],
        sources,
      },
    };
  }

  let visualContextNote = "";
  if (Array.isArray(pageImagesBase64) && pageImagesBase64.length > 0) {
    const descriptions: string[] = [];
    for (const img of pageImagesBase64.slice(0, 2)) {
      const desc = await describeImageWithOllama(img.base64, prompt);
      if (desc) {
        descriptions.push(
          `[ANALYSE VISUELLE PAGE ${img.pageNumber}${
            img.documentTitle ? ` (${img.documentTitle})` : ""
          }]\n${desc}`
        );
      }
    }
    if (descriptions.length > 0) {
      visualContextNote = `${descriptions.join("\n\n")}\n\n`;
    }
  }

  const contextText = truncateToContextBudget(
    visualContextNote + formatChunksForPrompt(orderedChunks, 900, 10),
    2000,
    12000
  );

  const customContextBlock = prompt?.trim()
    ? `\nOBJECTIF ET CONTEXTE PRIORITAIRE DE L'ÉTUDIANT :\n« ${prompt.trim()} »\nAdapte impérativement les explications, exemples et questions à ce que l'étudiant cherche à comprendre.\n`
    : "";

  if (kind === "SVG_DIAGRAM") {
    onProgress?.(20, "Génération du schéma vectoriel .SVG...");
    const aiDiagram = await callOllamaJson<{
      title?: string;
      subtitle?: string;
      layout?: "FLOW" | "HIERARCHY" | "RADIAL";
      nodes?: SvgNodeSpec[];
      edges?: SvgEdgeSpec[];
    }>(
      `À partir des extraits de cours ci-dessous, conçois un schéma conceptuel rigoureux en français sur : "${defaultTopic}".
${customContextBlock}
DESCRIPTION DES CHAMPS JSON ATTENDUS :
- "title" : titre court et précis résumant le sujet exact du schéma.
- "subtitle" : sous-titre académique précisant le domaine scientifique traité.
- "layout" : une valeur parmi "FLOW", "HIERARCHY" ou "RADIAL".
- "nodes" : tableau de 4 à 6 nœuds maximum, chacun contenant :
  - "id" : identifiant séquentiel ("n1" à "n6").
  - "code" : repère court d'étape ou de catégorie tiré du cours.
  - "label" : intitulé exact du concept tiré du document.
  - "detail" : explication factuelle concise (8 à 14 mots) fondée sur le cours.
- "edges" : tableau de liaisons entre nœuds, chacune contenant "from", "to" (identifiants de nœuds existants) et "label" (relation causale ou fonctionnelle réelle issue du cours).

EXTRAITS DU COURS :
${contextText}`,
      {
        system:
          "Tu es Spix, professeur universitaire vétérinaire spécialisé dans la synthèse visuelle scientifique.",
        format: SVG_DIAGRAM_SCHEMA,
        numPredict: 1400,
      }
    );

    let nodes: SvgNodeSpec[] = [];
    let edges: SvgEdgeSpec[] = [];
    let diagramTitle = params.title?.trim() || `Schéma : ${defaultTopic}`;
    let subtitle = `${chunks[0]?.ueCode || "ARA"} · ${chunks[0]?.documentTitle || "COURS"}`;
    let layout: "FLOW" | "HIERARCHY" | "RADIAL" = "FLOW";
    let usedAi = false;

    const validAiNodes = Array.isArray(aiDiagram?.nodes)
      ? aiDiagram.nodes.filter(
          (n) =>
            n?.label &&
            !hasGenericPlaceholderLeak(n.label) &&
            !hasGenericPlaceholderLeak(n.detail)
        )
      : [];

    if (validAiNodes.length >= 2) {
      usedAi = true;
      nodes = validAiNodes.slice(0, 6).map((n, idx) => ({
        id: n.id || `n${idx + 1}`,
        code: n.code || `0${idx + 1}`,
        label: n.label || `Concept ${idx + 1}`,
        detail: n.detail || "",
        color: SWISS_COLORS[idx % SWISS_COLORS.length],
      }));
      edges = Array.isArray(aiDiagram?.edges)
        ? aiDiagram.edges.filter((e) => !hasGenericPlaceholderLeak(e.label))
        : [];
      if (aiDiagram?.title && !hasGenericPlaceholderLeak(aiDiagram.title)) {
        diagramTitle = aiDiagram.title;
      }
      if (aiDiagram?.subtitle && !hasGenericPlaceholderLeak(aiDiagram.subtitle)) {
        subtitle = aiDiagram.subtitle;
      }
      if (
        aiDiagram?.layout === "HIERARCHY" ||
        aiDiagram?.layout === "RADIAL" ||
        aiDiagram?.layout === "FLOW"
      ) {
        layout = aiDiagram.layout;
      }
    } else {
      const usedChunks = chunks.slice(0, 5);
      nodes = usedChunks.map((c, idx) => {
        const sents = splitSentences(c.content);
        const firstSent = sents[0] || c.content.slice(0, 90);
        const shortLabel =
          firstSent.split(/\s+/).slice(0, 5).join(" ") || c.chapterTitle;
        return {
          id: `n${idx + 1}`,
          code: `${c.ueCode} · P.${c.pageNumber}`,
          label: shortLabel,
          detail: firstSent,
          color: SWISS_COLORS[idx % SWISS_COLORS.length],
        };
      });
      edges = nodes.slice(0, -1).map((n, idx) => ({
        from: n.id,
        to: nodes[idx + 1].id,
        label: "suite",
      }));
    }

    const svg = compileSwissEditorialSvg({
      title: diagramTitle,
      subtitle,
      layout,
      nodes,
      edges,
      sources,
    });

    onProgress?.(100, "Schéma .SVG terminé");
    return {
      title: diagramTitle,
      usedAi,
      content: {
        kind: "SVG_DIAGRAM",
        title: diagramTitle,
        subtitle,
        layout,
        nodes,
        edges,
        svg,
        sources,
      },
    };
  }

  if (kind === "FLASHCARDS") {
    // Pack consecutive pages into dense context-safe windows (zero artificial over-splitting)
    const windows = fullCourseMode
      ? splitChunksIntoContextWindows(orderedChunks, {
          maxWords: 1750,
          maxChars: 10500,
          maxWindows: 25,
        })
      : splitChunksIntoContextWindows(orderedChunks.slice(0, 12), {
          maxWords: 1800,
          maxChars: 10500,
          maxWindows: 1,
        });

    const targetCount = fullCourseMode
      ? Math.min(72, Math.max(18, windows.length * 10))
      : 10;
    const title =
      params.title?.trim() ||
      (fullCourseMode
        ? `Flashcards complètes — ${chunks[0]?.documentTitle || defaultTopic}`
        : `Flashcards ciblées : ${defaultTopic}`);

    const flashcardsSystemPrompt = `Tu es un créateur de flashcards pédagogiques universitaires vétérinaires exigeant et rigoureux.
RÈGLES JSON STRICTES (objet contenant le tableau "cards") :
- "front" : une question directe, courte et autonome en une seule phrase (10 à 22 mots) portant sur une valeur exacte, un mécanisme, un rôle anatomique/physiologique ou une distinction réelle du document. Interdit de formuler une question méta sur la page ou de recopier une phrase brute.
- "back" : la réponse exacte, nette et concise en 1 à 2 phrases en mettant le terme ou la valeur clé en gras au début.
- "tag" : une catégorie thématique courte en majuscules adaptée à la discipline.
- "sourcePage" : l'entier correspondant au numéro de page exact [P.X] indiqué dans les extraits.`;

    const cards: FlashcardItem[] = [];
    const seenFronts = new Set<string>();
    let anyAiUsed = false;

    const runFlashcardPass = async (
      win: ContextWindow,
      passLabel: string,
      desiredCount: number,
      avoidHint = ""
    ) => {
      if (!hasUsableText(win.text)) return;

      const aiCards = await callOllamaJson<{
        cards?: Array<{
          front?: string;
          back?: string;
          tag?: string;
          sourcePage?: number;
        }>;
      }>(
        `Génère exactement ${desiredCount} flashcards de révision active fondées uniquement sur les faits, valeurs chiffrées, définitions, mécanismes et critères présents dans les extraits ci-dessous.
${passLabel}
${customContextBlock}${avoidHint}
EXTRAITS DU COURS (${win.pageRange}) :
${win.text}`,
        {
          system: flashcardsSystemPrompt,
          format: FLASHCARDS_SCHEMA,
          arrayKeys: ["cards"],
          numPredict: Math.min(2200, Math.max(700, desiredCount * 160)),
        }
      );

      if (
        aiCards?.cards &&
        Array.isArray(aiCards.cards) &&
        aiCards.cards.length > 0
      ) {
        for (let idx = 0; idx < aiCards.cards.length; idx += 1) {
          if (cards.length >= targetCount) break;
          const c = aiCards.cards[idx];
          if (!c.front || !c.back) continue;
          const cleanFront = String(c.front).trim();
          const cleanBack = String(c.back).trim();
          if (
            cleanFront.length < 10 ||
            cleanBack.length < 4 ||
            isLowQualityExcerptQuestion(cleanFront, undefined, cleanBack) ||
            hasGenericPlaceholderLeak(c.tag)
          ) {
            continue;
          }
          const normKey = cleanFront.toLowerCase().slice(0, 60);
          if (seenFronts.has(normKey)) continue;
          seenFronts.add(normKey);
          anyAiUsed = true;

          const src = resolveSourceChunkByPage(win.chunks, c.sourcePage, idx);
          cards.push({
            id: `fc-${cards.length + 1}-${crypto.randomUUID().slice(0, 4)}`,
            front: cleanFront,
            back: cleanBack,
            tag: String(c.tag || src?.ueCode || "NOTION CLÉ").trim(),
            documentId: src?.documentId || "",
            fileName: src?.fileName || "document.pdf",
            pageNumber: src?.pageNumber || 1,
            ueId: src?.ueId || "",
          });
        }
      }
    };

    const perWindowCount = fullCourseMode
      ? Math.max(8, Math.ceil(targetCount / Math.max(1, windows.length)))
      : 10;

    for (let sIdx = 0; sIdx < windows.length; sIdx += 1) {
      if (shouldStop?.() || cards.length >= targetCount) break;

      const win = windows[sIdx];
      onProgress?.(
        Math.round((sIdx / Math.max(1, windows.length)) * 100),
        `Flashcards (${win.pageRange} · Lot ${sIdx + 1}/${windows.length})`
      );

      const scopeHint = fullCourseMode
        ? `PARTIE ${sIdx + 1}/${windows.length} DU COURS (${win.pageRange}) : couvre les valeurs, définitions et mécanismes clés présents dans ces pages.`
        : "Focus ciblé et exigeant sur la notion demandée par l'étudiant.";

      await runFlashcardPass(win, scopeHint, perWindowCount);
    }

    // Single AI top-up pass only if significantly below targetCount (< 75%)
    if (
      anyAiUsed &&
      cards.length < Math.ceil(targetCount * 0.75) &&
      !shouldStop?.() &&
      windows.length > 0
    ) {
      const deficit = Math.min(10, targetCount - cards.length);
      const topUpWin = windows[0];
      const avoidList = cards
        .slice(-8)
        .map((c) => c.front)
        .join(" | ");
      await runFlashcardPass(
        topUpWin,
        `COMPLÉMENT (${deficit} nouvelles flashcards distinctes) : explore d'autres faits, chiffres ou mécanismes présents dans le texte non encore traités.`,
        deficit,
        avoidHintFromList(avoidList)
      );
    }

    // Emergency factual extractor fallback only if still incomplete (never raw poly chunks)
    if (cards.length < targetCount && (anyAiUsed || !shouldStop?.())) {
      const factCards = buildFactFlashcardsFromChunks(
        orderedChunks,
        targetCount - cards.length,
        seenFronts
      );
      for (const fc of factCards) {
        if (cards.length >= targetCount) break;
        cards.push({
          id: `fc-${cards.length + 1}-${crypto.randomUUID().slice(0, 4)}`,
          ...fc,
        });
      }
    }

    onProgress?.(100, `${cards.length} flashcards générées`);
    return {
      title,
      usedAi: anyAiUsed,
      content: {
        kind: "FLASHCARDS",
        cards: cards.slice(0, targetCount),
        sources,
      },
    };
  }

  if (kind === "QUIZ") {
    // Pack consecutive pages into dense context-safe windows (zero artificial over-splitting)
    const windows = fullCourseMode
      ? splitChunksIntoContextWindows(orderedChunks, {
          maxWords: 1750,
          maxChars: 10500,
          maxWindows: 20,
        })
      : splitChunksIntoContextWindows(orderedChunks.slice(0, 12), {
          maxWords: 1800,
          maxChars: 10500,
          maxWindows: 1,
        });

    const targetCount = fullCourseMode
      ? Math.min(45, Math.max(12, windows.length * 7))
      : 6;
    const title =
      params.title?.trim() ||
      (fullCourseMode
        ? `Quiz complet (${targetCount} Q) — ${chunks[0]?.documentTitle || defaultTopic}`
        : `Quiz ciblé : ${defaultTopic}`);

    const quizSystemPrompt = `Tu es un concepteur d'examens universitaires vétérinaires rigoureux.
RÈGLES JSON STRICTES (objet contenant le tableau "questions") :
Chaque élément de "questions" doit contenir :
- "type" : "QCU" (majoritaire, une seule bonne réponse), "QCM" (2 ou 3 bonnes réponses) ou "QROC" (question ouverte à réponse courte exacte).
- "prompt" : énoncé interrogatif direct, autonome et contextualisé portant sur un fait précis du cours (interdit de recopier des phrases du polycopié en propositions ou de demander quelle phrase figure dans le cours).
- "options" : pour QCU et QCM, un tableau de exactement 4 propositions courtes (1 à 10 mots chacune), homogènes entre elles, plausibles et sans préfixe alphabétique ; pour QROC, un tableau vide.
- "correctIndices" : pour QCU, un tableau contenant l'unique indice entier (0 à 3) de la bonne réponse en variant la position ; pour QCM, 2 ou 3 indices entiers (0 à 3) ; pour QROC, un tableau vide.
- "correctAnswer" : pour QROC uniquement, la réponse exacte attendue en 1 à 4 mots tirée du cours ; chaîne vide pour QCU/QCM.
- "acceptedKeywords" : pour QROC uniquement, liste des mots-clés scientifiques exacts et synonymes acceptés tirés du cours ; tableau vide pour QCU/QCM.
- "explanation" : justification pédagogique concise rédigée à partir des faits précis du cours.
- "sourcePage" : entier correspondant au numéro de page exact [P.X] figurant dans les extraits.`;

    const questions: RevisionQuestion[] = [];
    const seenPrompts = new Set<string>();
    let anyAiUsed = false;

    const runQuizPass = async (
      win: ContextWindow,
      passLabel: string,
      batchSize: number,
      avoidHint = ""
    ) => {
      if (!hasUsableText(win.text)) return;

      const aiQuiz = await callOllamaJson<{
        questions?: Array<{
          type?: "QCU" | "QCM" | "QROC" | "FILL_BLANK";
          prompt?: string;
          options?: string[];
          correctIndices?: number[];
          sentenceWithBlank?: string;
          correctAnswer?: string;
          acceptedKeywords?: string[];
          distractors?: string[];
          explanation?: string;
          sourcePage?: number;
        }>;
      }>(
        `Génère exactement ${batchSize} questions d'examen originales et précises testant les valeurs, seuils, définitions et mécanismes scientifiques extraits du cours ci-dessous.
${passLabel}
${customContextBlock}${avoidHint}
EXTRAITS DU COURS (${win.pageRange}) :
${win.text}`,
        {
          system: quizSystemPrompt,
          format: STUDIO_QUIZ_SCHEMA,
          arrayKeys: ["questions"],
          numPredict: Math.min(2400, Math.max(800, batchSize * 240)),
        }
      );

      if (
        aiQuiz?.questions &&
        Array.isArray(aiQuiz.questions) &&
        aiQuiz.questions.length > 0
      ) {
        for (let idx = 0; idx < aiQuiz.questions.length; idx += 1) {
          if (questions.length >= targetCount) break;
          const q = aiQuiz.questions[idx];
          const src = resolveSourceChunkByPage(win.chunks, q.sourcePage, idx);
          if (!src || !q.prompt) continue;

          const cleanPrompt = q.prompt.trim();
          const promptKey = cleanPrompt.toLowerCase().slice(0, 60);
          if (seenPrompts.has(promptKey)) continue;
          if (hasGenericPlaceholderLeak(q.explanation)) continue;

          if (
            (q.type === "QCU" || q.type === "QCM") &&
            Array.isArray(q.options) &&
            q.options.length === 4 &&
            Array.isArray(q.correctIndices)
          ) {
            const cleanOpts = q.options.map((o) =>
              stripOptionLetterPrefix(String(o))
            );
            if (isLowQualityExcerptQuestion(cleanPrompt, cleanOpts)) continue;

            const validIndices = Array.from(
              new Set(
                q.correctIndices.filter(
                  (i) => typeof i === "number" && i >= 0 && i < 4
                )
              )
            ).sort((a, b) => a - b);

            if (validIndices.length > 0) {
              const targetIndices =
                q.type === "QCU" ? [validIndices[0]] : validIndices;
              const shuffled = shuffleOptionsWithIndices(cleanOpts, targetIndices);
              seenPrompts.add(promptKey);
              anyAiUsed = true;
              questions.push({
                id: `sq-${questions.length + 1}`,
                type: q.type,
                ueId: src.ueId,
                ueCode: src.ueCode,
                ueTitle: src.ueTitle,
                chapterTitle: src.chapterTitle,
                documentId: src.documentId,
                documentTitle: src.documentTitle,
                fileName: src.fileName,
                pageNumber: src.pageNumber,
                prompt: cleanPrompt,
                options: shuffled.options,
                correctIndices: shuffled.correctIndices,
                explanation:
                  q.explanation?.trim() ||
                  `Source : ${src.documentTitle} (p.${src.pageNumber}).`,
                generatedByAi: true,
              });
            }
          } else if (
            q.type === "QROC" &&
            typeof q.correctAnswer === "string" &&
            q.correctAnswer.trim().length > 0 &&
            !isLowQualityExcerptQuestion(cleanPrompt, undefined, q.correctAnswer)
          ) {
            seenPrompts.add(promptKey);
            anyAiUsed = true;
            const mainAnswer = q.correctAnswer.trim();
            const kw = Array.isArray(q.acceptedKeywords)
              ? q.acceptedKeywords
                  .map((k) => String(k).trim())
                  .filter((k) => k.length > 0 && !hasGenericPlaceholderLeak(k))
              : [];
            questions.push({
              id: `sq-${questions.length + 1}`,
              type: "QROC",
              ueId: src.ueId,
              ueCode: src.ueCode,
              ueTitle: src.ueTitle,
              chapterTitle: src.chapterTitle,
              documentId: src.documentId,
              documentTitle: src.documentTitle,
              fileName: src.fileName,
              pageNumber: src.pageNumber,
              prompt: cleanPrompt,
              correctAnswer: mainAnswer,
              acceptedKeywords: Array.from(new Set([mainAnswer, ...kw])),
              explanation:
                q.explanation?.trim() ||
                `Réponse attendue : « ${mainAnswer} » (p.${src.pageNumber}).`,
              generatedByAi: true,
            });
          } else if (
            q.type === "FILL_BLANK" &&
            q.sentenceWithBlank &&
            q.correctAnswer &&
            !isLowQualityExcerptQuestion(cleanPrompt, undefined, q.correctAnswer)
          ) {
            seenPrompts.add(promptKey);
            anyAiUsed = true;
            const bank = [
              q.correctAnswer,
              ...(Array.isArray(q.distractors) ? q.distractors.slice(0, 3) : []),
            ];
            questions.push({
              id: `sq-${questions.length + 1}`,
              type: "FILL_BLANK",
              ueId: src.ueId,
              ueCode: src.ueCode,
              ueTitle: src.ueTitle,
              chapterTitle: src.chapterTitle,
              documentId: src.documentId,
              documentTitle: src.documentTitle,
              fileName: src.fileName,
              pageNumber: src.pageNumber,
              prompt: cleanPrompt,
              sentenceWithBlank: q.sentenceWithBlank,
              correctAnswer: q.correctAnswer,
              wordBank: bank,
              explanation:
                q.explanation?.trim() ||
                `Terme attendu : « ${q.correctAnswer} » (p.${src.pageNumber}).`,
              generatedByAi: true,
            });
          }
        }
      }
    };

    const batchSizePerWindow = fullCourseMode
      ? Math.max(6, Math.ceil(targetCount / Math.max(1, windows.length)))
      : 6;

    for (let sIdx = 0; sIdx < windows.length; sIdx += 1) {
      if (shouldStop?.() || questions.length >= targetCount) break;

      const win = windows[sIdx];
      onProgress?.(
        Math.round((sIdx / Math.max(1, windows.length)) * 100),
        `Quiz (${win.pageRange} · Lot ${sIdx + 1}/${windows.length})`
      );

      const scopeHint = fullCourseMode
        ? `PARTIE ${sIdx + 1}/${windows.length} DU COURS (${win.pageRange}) : interroge les notions, chiffres et mécanismes clés présents dans ces pages.`
        : "Focus ciblé et exigeant sur ce que l'étudiant cherche à comprendre.";

      await runQuizPass(win, scopeHint, batchSizePerWindow);
    }

    // Single AI top-up pass only if significantly below targetCount (< 75%)
    if (
      anyAiUsed &&
      questions.length < Math.ceil(targetCount * 0.75) &&
      !shouldStop?.() &&
      windows.length > 0
    ) {
      const deficit = Math.min(6, targetCount - questions.length);
      const topUpWin = windows[0];
      const avoidList = questions
        .slice(-6)
        .map((q) => q.prompt)
        .join(" | ");
      await runQuizPass(
        topUpWin,
        `COMPLÉMENT (${deficit} nouvelles questions distinctes) : interroge d'autres valeurs, cas ou notions non encore posés.`,
        deficit,
        avoidHintFromList(avoidList)
      );
    }

    // Emergency factual/value fallback (zero raw poly paragraph copying)
    if (questions.length < targetCount && (anyAiUsed || !shouldStop?.())) {
      const factQuestions = buildFactQuestionsFromChunks(
        orderedChunks,
        targetCount - questions.length,
        seenPrompts
      );
      for (const fq of factQuestions) {
        if (questions.length >= targetCount) break;
        questions.push({
          ...fq,
          id: `sq-${questions.length + 1}`,
        });
      }
    }

    onProgress?.(100, `${questions.length} questions générées`);
    return {
      title,
      usedAi: anyAiUsed,
      content: {
        kind: "QUIZ",
        questions: questions.slice(0, targetCount),
        sources,
      },
    };
  }

  // SUMMARY: Full-course structured "Fiche de Révision Ultime" (public 95%) vs targeted (private 5%)
  const title =
    params.title?.trim() ||
    (fullCourseMode
      ? `Fiche de Révision Ultime — ${chunks[0]?.documentTitle || defaultTopic}`
      : `Fiche Ciblée : ${defaultTopic}`);

  // Context-window-safe sequential splitting covering the ENTIRE handout (no 8-window truncation!)
  const windows = splitChunksIntoContextWindows(
    orderedChunks,
    fullCourseMode
      ? { maxWords: 1800, maxChars: 11000, maxWindows: 40 }
      : { maxWords: 2000, maxChars: 12000, maxWindows: 3 }
  );

  const sections: SummarySection[] = [];
  const allConcepts: SummaryPayload["keyConcepts"] = [];
  const seenTerms = new Set<string>();
  const allPitfalls: string[] = [];
  const seenPitfalls = new Set<string>();
  let anyAiUsed = false;

  // Static system prompt kept identical across all windows & documents for Ollama KV-cache prefix reuse
  const summarySystemPrompt = `Tu es un major de promotion vétérinaire qui rédige une fiche de révision universitaire exhaustive, rigoureuse et strictement fidèle aux extraits de cours fournis.

RÈGLES IMPÉRATIVES :
1. Conserve 100 % des notions scientifiques réelles du texte : définitions, molécules, hormones, récepteurs, mécanismes, organes, classifications, abréviations expliquées, valeurs chiffrées et exceptions.
2. Ignore totalement les bruits de diapositives : numéros de pages isolés, questions orales de l'enseignant, références bibliographiques et en-têtes répétés.
3. N'invente aucune donnée absente du texte. N'insère un tableau Markdown que lorsque le passage compare réellement au moins deux entités scientifiques distinctes, sans jamais répéter de ligne.
4. Ne place dans la rubrique des pièges que des confusions ou exceptions réellement présentes dans ces pages.

SYNTAXE MARKDOWN OBLIGATOIRE (Markdown pur, sans JSON) :
- Première ligne : le préfixe "TITRE:" suivi du titre précis de cette section du cours.
- Ensuite 3 à 5 sous-parties introduites chacune par un titre Markdown niveau 2 ("##") suivi d'un emoji thématique pertinent et de l'intitulé réel de la sous-partie.
- Utilise des citations Markdown (">") avec l'emoji 💡 pour une définition exacte et l'emoji ⚠️ pour une règle majeure ou un seuil chiffré tiré du cours.
- Rédige au moins 4 puces Markdown ("-") détaillées par sous-partie, en mettant en gras le nom du concept réel suivi de deux-points et de son explication complète (avec sous-puces indentées de deux espaces pour les exceptions ou précisions).
- Ajoute un tableau Markdown uniquement si le cours compare explicitement plusieurs entités réelles.
- Termine par une ligne "PIÈGES:" suivie d'une liste à puces des distinctions et pièges réels issus du passage.`;

  const buildSummaryPrompt = (
    winText: string,
    pageRange: string,
    wIdx: number,
    totalWindows: number
  ) => {
    const scope = fullCourseMode
      ? `PARTIE ${wIdx + 1}/${totalWindows} du polycopié (pages ${pageRange}) : rédige la fiche complète de ces pages.`
      : "Réponds précisément à la demande de l'étudiant à partir de ces extraits.";

    return `${scope}${customContextBlock ? `\n${customContextBlock}` : ""}

EXTRAITS DU COURS (pages ${pageRange}) :
${winText}`;
  };

  for (let wIdx = 0; wIdx < windows.length; wIdx += 1) {
    if (shouldStop?.()) break;

    const win = windows[wIdx];
    onProgress?.(
      Math.round((wIdx / Math.max(1, windows.length)) * 100),
      fullCourseMode
        ? `Fiche ultime (${win.pageRange} · partie ${wIdx + 1}/${windows.length})`
        : "Rédaction de la fiche ciblée..."
    );

    const scoreRichness = (p: ParsedSummaryMarkdown | null) =>
      p
        ? p.subsections.reduce(
            (n, s) =>
              n +
              (s.bullets?.length || 0) +
              (s.callouts?.length || 0) +
              (s.table ? 2 : 0),
            0
          )
        : 0;

    let md = await callOllamaText(
      buildSummaryPrompt(win.text, win.pageRange, wIdx, windows.length),
      {
        system: summarySystemPrompt,
        numPredict: 1700,
        timeoutMs: OLLAMA_TIMEOUT_MS,
        shouldStop,
      }
    );
    let parsed = md ? parseSummaryMarkdown(md) : null;
    let aiOk = Boolean(parsed) && scoreRichness(parsed) >= 3;

    // Automatic single retry with condensed high-value text if first attempt failed
    if (!aiOk && !shouldStop?.()) {
      const condensed = selectHighValueText(win.text, 4500);
      md = await callOllamaText(
        buildSummaryPrompt(condensed, win.pageRange, wIdx, windows.length),
        {
          system: summarySystemPrompt,
          numPredict: 1300,
          timeoutMs: OLLAMA_TIMEOUT_MS,
          shouldStop,
        }
      );
      parsed = md ? parseSummaryMarkdown(md) : null;
      aiOk = Boolean(parsed) && scoreRichness(parsed) >= 3;
    }

    const subsections: SummarySubSection[] = aiOk
      ? [...parsed!.subsections]
      : [];

    let sectionTitle: string;
    if (aiOk) {
      anyAiUsed = true;
      sectionTitle =
        parsed!.title ||
        `Partie ${wIdx + 1} · ${win.chunks[0]?.chapterTitle || "Cours"}`;

      let taken = 0;
      for (const sub of parsed!.subsections) {
        for (const b of sub.bullets || []) {
          if (!b.lead || taken >= 4) continue;
          const key = b.lead.toLowerCase();
          if (seenTerms.has(key)) continue;
          seenTerms.add(key);
          const needle = key.slice(0, 30);
          const src =
            win.chunks.find((c) => c.content.toLowerCase().includes(needle)) ||
            win.chunks[0];
          allConcepts.push({
            term: b.lead,
            definition: b.text,
            sourceLabel: `[${src.fileName.toUpperCase()} · P.${src.pageNumber}]`,
            documentId: src.documentId,
            pageNumber: src.pageNumber,
            ueId: src.ueId,
          });
          taken += 1;
        }
      }

      for (const p of parsed!.pitfalls) {
        const pKey = p.toLowerCase().slice(0, 50);
        if (p && !seenPitfalls.has(pKey)) {
          seenPitfalls.add(pKey);
          allPitfalls.push(p);
        }
      }
    } else {
      // IA unavailable for this window: extract clean definitions/facts & densest lines
      sectionTitle = `Partie ${wIdx + 1} · ${
        win.chunks[0]?.chapterTitle || "Cours"
      } (résumé automatique — IA indisponible)`;
      const { definitions, quantFacts } = extractCourseFacts(win.chunks);
      if (definitions.length > 0) {
        subsections.push({
          icon: "🎯",
          title: "Définitions & Notions relevées",
          bullets: definitions.slice(0, 8).map((d) => ({
            lead: d.term,
            text: d.explanation,
          })),
        });
      }
      if (quantFacts.length > 0) {
        subsections.push({
          icon: "📊",
          title: "Valeurs & Seuils relevés",
          callouts: [
            {
              type: "KEY_DATE",
              icon: "⚠️",
              title: "Repères chiffrés du cours",
              items: quantFacts
                .slice(0, 5)
                .map(
                  (q) =>
                    `**${q.exactValue}** — ${q.contextSentence.replace(
                      "[ ... ]",
                      q.exactValue
                    )}`
                ),
            },
          ],
        });
      }
      const dense = splitSentences(selectHighValueText(win.text, 1600)).slice(
        0,
        8
      );
      if (subsections.length === 0) {
        subsections.push({
          icon: "📜",
          title: "Points clés des pages",
          bullets: dense.map((s) => ({ text: s })),
        });
      }
    }

    const firstSub = subsections[0];
    const summaryText =
      firstSub?.intro ||
      firstSub?.callouts?.[0]?.text ||
      firstSub?.bullets?.[0]?.text ||
      "";
    const keyPoints = subsections
      .flatMap((s) => s.bullets || [])
      .slice(0, 5)
      .map((b) => (b.lead ? `${b.lead} : ${b.text}` : b.text));

    sections.push({
      title: sectionTitle,
      pageRange: win.pageRange,
      content: summaryText,
      keyPoints,
      subsections,
    });
  }

  const maxConcepts = fullCourseMode ? 40 : 7;
  const maxPitfalls = fullCourseMode ? 20 : 5;

  if (allConcepts.length === 0) {
    for (const c of orderedChunks.slice(0, 4)) {
      allConcepts.push({
        term: c.chapterTitle,
        definition: splitSentences(c.content)[0] || c.content.slice(0, 180),
        sourceLabel: `[${c.fileName.toUpperCase()} · P.${c.pageNumber}]`,
        documentId: c.documentId,
        pageNumber: c.pageNumber,
        ueId: c.ueId,
      });
    }
  }

  if (allPitfalls.length === 0) {
    allPitfalls.push(
      "Vérifier les définitions exactes et les seuils numériques dans les polycopiés officiels.",
      "Relier chaque mécanisme aux schémas présentés en cours."
    );
  }

  const cleanOverview = fullCourseMode
    ? `Fiche de révision complète structurée en ${sections.length} chapitre${
        sections.length > 1 ? "s" : ""
      } couvrant l'intégralité du polycopié (${computePageRangeLabel(
        orderedChunks
      )}).`
    : `Fiche de révision ciblée sur « ${defaultTopic} » (${computePageRangeLabel(
        orderedChunks
      )}).`;

  onProgress?.(100, "Fiche de révision complète générée");
  return {
    title,
    usedAi: anyAiUsed,
    content: {
      kind: "SUMMARY",
      pipeline: "FULL_V3",
      overview: cleanOverview,
      sections,
      keyConcepts: allConcepts.slice(0, maxConcepts),
      examPitfalls: allPitfalls.slice(0, maxPitfalls),
      sources,
    },
  };
}

export function isStalePublicArtifact(
  kind: StudioArtifactKind | string,
  contentJson: string
): boolean {
  try {
    const parsed = JSON.parse(contentJson) as Partial<StudioArtifactContent> & {
      questions?: RevisionQuestion[];
      cards?: FlashcardItem[];
      sections?: SummarySection[];
      pipeline?: string;
    };
    if (kind === "QUIZ") {
      const qs = Array.isArray(parsed.questions) ? parsed.questions : [];
      if (qs.length === 0) return true;
      const anyAi = qs.some((q) => Boolean(q.generatedByAi));
      if (!anyAi) return true;
      return qs.some(
        (q) =>
          isLowQualityExcerptQuestion(
            q.prompt || "",
            q.options,
            q.correctAnswer || q.flashcardBack
          ) || hasGenericPlaceholderLeak(q.explanation)
      );
    }
    if (kind === "FLASHCARDS") {
      const cards = Array.isArray(parsed.cards) ? parsed.cards : [];
      if (cards.length === 0) return true;
      return cards.some(
        (c) =>
          /notion clé\s*\(|quel élément faut-il maîtriser/i.test(c.front || "") ||
          hasGenericPlaceholderLeak(c.front) ||
          hasGenericPlaceholderLeak(c.back)
      );
    }
    if (kind === "SUMMARY") {
      // Rebuild pre-V3 summaries or any summary that fell back to non-AI extraction
      if (parsed.pipeline !== "FULL_V3") return true;
      const secs = Array.isArray(parsed.sections) ? parsed.sections : [];
      if (secs.length === 0) return true;
      if (secs.some((s) => /IA indisponible/i.test(s.title || ""))) return true;
      if (
        secs.some(
          (s) =>
            hasGenericPlaceholderLeak(s.title) ||
            (s.subsections || []).some(
              (sub) =>
                hasGenericPlaceholderLeak(sub.title) ||
                (sub.bullets || []).some(
                  (b) =>
                    hasGenericPlaceholderLeak(b.lead) ||
                    hasGenericPlaceholderLeak(b.text)
                )
            )
        )
      ) {
        return true;
      }
      return !secs.some(
        (s) => Array.isArray(s.subsections) && s.subsections.length > 0
      );
    }
    return false;
  } catch {
    return true;
  }
}

async function findValidPublicArtifactId(
  documentId: string,
  kind: StudioArtifactKind
): Promise<{ validId: string | null; staleId: string | null }> {
  const rows = await prisma.studyArtifact.findMany({
    where: {
      documentId,
      kind,
      isPublic: true,
    },
    orderBy: { createdAt: "desc" },
    select: { id: true, contentJson: true },
  });
  for (const r of rows) {
    if (!isStalePublicArtifact(kind, r.contentJson)) {
      return { validId: r.id, staleId: null };
    }
  }
  return { validId: null, staleId: rows[0]?.id || null };
}

export async function hasExistingPublicArtifact(
  documentId: string | null | undefined,
  kind: StudioArtifactKind
): Promise<boolean> {
  if (!documentId) return false;
  await ensureStudioSchema();
  const { validId } = await findValidPublicArtifactId(documentId, kind);
  return Boolean(validId);
}

